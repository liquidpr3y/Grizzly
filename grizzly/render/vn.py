"""Visual novel exports: a Ren'Py script and a standalone HTML player."""

from __future__ import annotations

import html
import json
import shutil
from pathlib import Path

from grizzly.models import Project

_PALETTE = ["#f4a261", "#8ecae6", "#e9c46a", "#b5e48c", "#ffafcc", "#cdb4db"]


def _rpy_str(text: str) -> str:
    # Ren'Py treats [ and { as interpolation / text tags.
    text = text.replace("\\", "\\\\").replace('"', '\\"').replace("[", "[[").replace("{", "{{")
    return f'"{text}"'


def build_renpy(project: Project, root: Path) -> Path:
    game = root / "exports" / "renpy" / "game"
    images = game / "images"
    images.mkdir(parents=True, exist_ok=True)
    bible = project.bible
    lines = [f"# {bible.title} - generated by Grizzly", ""]
    for i, c in enumerate(bible.characters):
        lines.append(f'define c_{c.id} = Character({_rpy_str(c.name)}, color="{_PALETTE[i % len(_PALETTE)]}")')
    lines.append("")
    for shot in project.shots:
        if shot.image and (root / shot.image).exists():
            shutil.copy(root / shot.image, images / f"{shot.id}.png")
            lines.append(f'image shot_{shot.id} = "images/{shot.id}.png"')
    lines += ["", "label start:", ""]
    scene_id = None
    for shot in project.shots:
        if shot.scene_id != scene_id:
            scene_id = shot.scene_id
            lines.append(f"    # Scene {scene_id}")
        if shot.image:
            lines.append(f"    scene shot_{shot.id} with dissolve")
        if shot.narration:
            lines.append(f"    {_rpy_str(shot.narration)}")
        for line in shot.dialogue:
            who = f"c_{line.speaker} " if bible.character(line.speaker) else ""
            lines.append(f"    {who}{_rpy_str(line.text)}")
        if not shot.narration and not shot.dialogue:
            lines.append("    pause 2.0")
    lines += ["", "    return", ""]
    script = game / "script.rpy"
    script.write_text("\n".join(lines))
    return script


_PLAYER = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>__TITLE__</title>
<style>
  :root { color-scheme: dark; }
  body { margin: 0; background: #0b0b0f; color: #eee; font: 18px/1.5 -apple-system, system-ui, sans-serif; }
  #stage { position: relative; width: 100vw; height: 100vh; overflow: hidden; cursor: pointer; }
  #bg { position: absolute; inset: 0; width: 100%; height: 100%; object-fit: cover; transition: opacity .4s; }
  #box { position: absolute; left: 4%; right: 4%; bottom: 4%; min-height: 110px; padding: 18px 24px;
         background: rgba(10,10,16,.82); border: 1px solid #ffffff22; border-radius: 12px; }
  #who { font-weight: 700; margin-bottom: 4px; }
  #hint { position: absolute; right: 16px; bottom: 8px; font-size: 12px; opacity: .5; }
  .narr #text { font-style: italic; }
</style></head>
<body><div id="stage"><img id="bg" alt=""><div id="box"><div id="who"></div><div id="text"></div>
<div id="hint">click / space to continue, &larr; to go back</div></div></div>
<script>
const beats = __BEATS__;
let i = 0;
const bg = document.getElementById("bg"), who = document.getElementById("who"), text = document.getElementById("text"), box = document.getElementById("box");
function show() {
  const b = beats[i];
  if (b.image && bg.getAttribute("src") !== b.image) bg.src = b.image;
  who.textContent = b.who || ""; who.style.color = b.color || "#fff";
  text.textContent = b.text || "";
  box.classList.toggle("narr", !b.who);
  box.style.display = b.text ? "" : "none";
}
function step(d) { i = Math.max(0, Math.min(beats.length - 1, i + d)); show(); }
document.getElementById("stage").addEventListener("click", () => step(1));
document.addEventListener("keydown", e => { if (e.key === " " || e.key === "ArrowRight") step(1); if (e.key === "ArrowLeft") step(-1); });
show();
</script></body></html>
"""


def build_html_player(project: Project, root: Path) -> Path:
    out = root / "exports" / "vn_html"
    (out / "images").mkdir(parents=True, exist_ok=True)
    bible = project.bible
    colors = {c.id: _PALETTE[i % len(_PALETTE)] for i, c in enumerate(bible.characters)}
    beats = []
    for shot in project.shots:
        image = None
        if shot.image and (root / shot.image).exists():
            shutil.copy(root / shot.image, out / "images" / f"{shot.id}.png")
            image = f"images/{shot.id}.png"
        texts = ([("", shot.narration)] if shot.narration else []) + [(d.speaker, d.text) for d in shot.dialogue]
        for speaker, line in texts or [("", "")]:
            c = bible.character(speaker) if speaker else None
            beats.append({"image": image, "who": c.name if c else "", "color": colors.get(c.id) if c else None, "text": line})
    page = _PLAYER.replace("__TITLE__", html.escape(bible.title)).replace(
        "__BEATS__", json.dumps(beats).replace("</", "<\\/")
    )
    path = out / "index.html"
    path.write_text(page)
    return path
